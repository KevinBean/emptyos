def test_cli_json_envelope(tmp_path, capsys):
    root = tmp_path / "projects"
    _corpus(root)
    rc = mc.main(
        [
            "--root", str(root),
            "--state", str(tmp_path / "state.json"),
            "--json", "--min-lift", "1.0", "--min-count", "3", "--min-sessions", "2",
        ]
    )
    payload = json.loads(capsys.readouterr().out)
    assert set(payload) == {"ok", "code", "message", "data"}
    assert rc == 1 and payload["ok"] is False, "findings mean not-ok, per agent-cli"
    assert payload["data"]["candidates"][0]["term"] == "browser"


def test_cli_dismiss_persists(tmp_path, capsys):
    root = tmp_path / "projects"
    _corpus(root)
    state = tmp_path / "state.json"
    common = ["--root", str(root), "--state", str(state), "--min-lift", "1.0"]

    mc.main(common + ["--json"])
    ids = [c["id"] for c in json.loads(capsys.readouterr().out)["data"]["candidates"]]
    cid = ids[0]

    for one in ids:
        mc.main(common + ["--json", "--dismiss", one[:6], "--note", "not a rule"])
        assert json.loads(capsys.readouterr().out)["data"]["status"] == "dismissed"

    rc = mc.main(common + ["--json"])
    out = json.loads(capsys.readouterr().out)
    assert rc == 0 and out["data"]["candidates"] == []
    assert json.loads(state.read_text(encoding="utf-8"))["clusters"][cid]["note"] == "not a rule"


