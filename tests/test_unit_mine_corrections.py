def test_real_turn_is_not_machine():
    assert not mc.is_machine_turn("no, you should use my session", "typed")


# ------------------------------------------------------------------ tokenizer


def test_contraction_stems_are_not_terms():
    """The word tokenizer splits on the apostrophe, so "don't" yields "don".
    That token appeared in a third of all corrections and produced the
    top-scoring cluster on the first run — a pure artifact."""
    terms = mc.salient_terms("don't do that, you shouldn't have, it won't work")
    for stem in ("don", "shouldn", "won"):
        assert stem not in terms, f"{stem!r} leaked into terms"


def test_cjk_bigrams_become_terms():
    assert "画面" in mc.salient_terms("不要这么现实的画面")


# ----------------------------------------------------------------------- lift


def test_lift_separates_theme_from_generic_verb():
    """Measured separation the threshold was set from: a term used only when
    correcting scores far above one that every request contains."""
    theme = mc.term_lift(corr_df=3, n_corr=37, global_df=11, n_turns=1700)
    verb = mc.term_lift(corr_df=3, n_corr=37, global_df=37, n_turns=1700)
    assert theme > mc.MIN_TERM_LIFT > verb


def test_generic_verb_seeds_no_cluster():
    """A word appearing in every ordinary request must not become a theme even
    when it appears in several corrections."""
    turns = [
        mc.Turn(uid=f"g{i}", text="can you change the layout", ts="", session="s", project="p", path="")
        for i in range(200)
    ]
    corr = [
        mc.Correction(
            turn=mc.Turn(
                uid=f"c{i}", text="no, you should change the layout", ts="", session=f"s{i}",
                project="p", path="",
            ),
            markers=("opening-no",),
        )
        for i in range(4)
    ]
    mc.assign_terms(corr, turns + [c.turn for c in corr])
    assert all("change" not in c.terms for c in corr)


# ------------------------------------------------------------ sweep + clusters


def _corpus(root: Path) -> None:
    """Three sessions, one recurring behaviour correction, plus noise."""
    write_transcript(
        root,
        "proj",
        "s1",
        [
            _rec("no, use the browser extension, not python in the console",
                 ts="2026-08-01T10:00:00Z", session="s1", uid="u1"),
            _rec("no, another one", ts="2026-08-01T10:05:00Z", session="s1", uid="u2"),
        ],
    )
    write_transcript(
        root,
        "proj",
        "s2",
        [
            _rec("you ignored my browser extension suggestion again",
                 ts="2026-08-05T10:00:00Z", session="s2", uid="u3"),
            _rec("Stop hook feedback:\n[go on]: nothing to report",
                 ts="2026-08-05T10:01:00Z", session="s2", uid="u4"),
        ],
    )
    write_transcript(
        root,
        "proj",
        "s3",
        [
            _rec("don't do that, the browser extension is the elegant way",
                 ts="2026-08-09T10:00:00Z", session="s3", uid="u5"),
        ],
    )


def test_sweep_finds_the_recurring_theme(tmp_path):
    root = tmp_path / "projects"
    _corpus(root)
    clusters, _, n_turns, n_corr = mc.sweep([root], {}, now="2026-08-10T00:00:00Z", min_lift=1.0)
    assert n_turns == 4, "machine turns must not be counted as human"
    assert n_corr == 3
    cands = mc.candidates(clusters, min_count=3, min_sessions=2, include_resolved=False)
    # Co-occurring terms both seed a cluster on purpose (see assign_terms):
    # the same evidence can support more than one candidate theme, and the
    # human picks by reading the quotes. Here "browser" and "extension" appear
    # together in all three corrections, so both are legitimate names for it.
    by_term = {c.term: c for c in cands}
    assert "browser" in by_term
    assert by_term["browser"].count == 3
    assert len(set(by_term["browser"].sessions)) == 3


def test_one_session_is_not_a_pattern(tmp_path):
    """Three corrections inside one conversation are one argument being had.
    ``min_sessions`` — not ``min_count`` — is what makes a theme durable."""
    root = tmp_path / "projects"
    write_transcript(
        root,
        "proj",
        "only",
        [
            _rec(f"no, you should use the browser extension ({i})",
                 ts=f"2026-08-0{i+1}T10:00:00Z", session="same", uid=f"x{i}")
            for i in range(3)
        ],
    )
    clusters, _, _, _ = mc.sweep([root], {}, now="2026-08-10T00:00:00Z", min_lift=1.0)
    assert mc.candidates(clusters, min_count=3, min_sessions=2, include_resolved=False) == []
    assert mc.candidates(clusters, min_count=3, min_sessions=1, include_resolved=False)


def test_rerunning_does_not_inflate_counts(tmp_path):
    """Lifetime counts accumulate across runs because transcripts rotate — so
    the seen-set is the only thing standing between that and double counting."""
    root = tmp_path / "projects"
    _corpus(root)
    state: dict = {}
    clusters, seen, _, _ = mc.sweep([root], state, now="2026-08-10T00:00:00Z", min_lift=1.0)
    state = mc.to_state(clusters, seen)
    first = {c.term: c.count for c in clusters.values()}

    clusters2, seen2, _, _ = mc.sweep([root], state, now="2026-08-10T00:00:00Z", min_lift=1.0)
    assert {c.term: c.count for c in clusters2.values()} == first


def test_count_survives_transcript_rotation(tmp_path):
    """The evidence rotates away; the count must not."""
    root = tmp_path / "projects"
    _corpus(root)
    clusters, seen, _, _ = mc.sweep([root], {}, now="2026-08-10T00:00:00Z", min_lift=1.0)
    state = mc.to_state(clusters, seen)

    for p in root.rglob("*.jsonl"):
        p.unlink()
    clusters2, _, n_turns, _ = mc.sweep([root], state, now="2026-09-20T00:00:00Z", min_lift=1.0)
    assert n_turns == 0
    kept = [c for c in clusters2.values() if c.term == "browser"]
    assert kept and kept[0].count == 3
    assert kept[0].quotes == [], "quotes are re-derived live, never persisted"


def test_dismissed_theme_stays_dismissed(tmp_path):
    """A dismissal is a durable decision — the whole point of persisting state."""
    root = tmp_path / "projects"
    _corpus(root)
    clusters, seen, _, _ = mc.sweep([root], {}, now="2026-08-10T00:00:00Z", min_lift=1.0)
    for c in clusters.values():
        c.status = "dismissed"
        c.note = "one-off"
    state = mc.to_state(clusters, seen)

    clusters2, _, _, _ = mc.sweep([root], state, now="2026-08-11T00:00:00Z", min_lift=1.0)
    again = next(c for c in clusters2.values() if c.term == "browser")
    assert again.status == "dismissed" and again.note == "one-off"
    assert mc.candidates(clusters2, min_count=3, min_sessions=2, include_resolved=False) == []
    assert mc.candidates(clusters2, min_count=3, min_sessions=2, include_resolved=True)


def test_state_holds_no_transcript_text(tmp_path):
    """Turn text must never reach disk — a second copy of transcript content is
    exactly what the deferred agent-transcript leak scan exists to worry about."""
    root = tmp_path / "projects"
    _corpus(root)
    clusters, seen, _, _ = mc.sweep([root], {}, now="2026-08-10T00:00:00Z", min_lift=1.0)
    blob = json.dumps(mc.to_state(clusters, seen))
    assert "browser extension" not in blob
    assert "python in the console" not in blob


