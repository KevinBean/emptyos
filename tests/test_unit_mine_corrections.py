# ------------------------------------------------------------------- aliases


def test_co_occurring_terms_collapse_to_one_candidate(tmp_path):
    """"browser" and "extension" appear in all three of the same corrections —
    one theme wearing two names. Reporting both means reading the same quotes
    twice and judging them twice."""
    root = tmp_path / "projects"
    _corpus(root)
    clusters, _, _, _ = mc.sweep([root], {}, now="2026-08-10T00:00:00Z", min_lift=1.0)
    raw = [c for c in clusters.values() if c.term in {"browser", "extension"}]
    assert len(raw) == 2, "both terms still get their own stable cluster id"

    cands = mc.candidates(clusters, min_count=3, min_sessions=2, include_resolved=False)
    assert len(cands) == 1
    assert cands[0].aliases, "the loser must be reported as an alias, not dropped silently"


def test_a_verdict_covers_the_whole_alias_group(tmp_path, capsys):
    """Dismissing one name while its alias stays open would resurface the same
    three quotes next sweep under a different word."""
    root = tmp_path / "projects"
    _corpus(root)
    state = tmp_path / "state.json"
    common = ["--root", str(root), "--state", str(state), "--min-lift", "1.0"]

    mc.main(common + ["--json"])
    cid = json.loads(capsys.readouterr().out)["data"]["candidates"][0]["id"]
    mc.main(common + ["--json", "--dismiss", cid[:6]])
    assert json.loads(capsys.readouterr().out)["data"]["aliases"]

    stored = json.loads(state.read_text(encoding="utf-8"))["clusters"]
    judged = {r["term"]: r["status"] for r in stored.values() if r["term"] in {"browser", "extension"}}
    assert judged == {"browser": "dismissed", "extension": "dismissed"}

    rc = mc.main(common + ["--json"])
    assert rc == 0 and json.loads(capsys.readouterr().out)["data"]["candidates"] == []


def test_rotated_evidence_never_groups(tmp_path):
    """An empty evidence set means "cannot be grouped", not "groups with every
    other empty one" — otherwise a rotation would merge unrelated themes."""
    a = mc.Cluster(cid="a", term="one", count=3, sessions=["s1", "s2"])
    b = mc.Cluster(cid="b", term="two", count=3, sessions=["s1", "s2"])
    clusters = {"a": a, "b": b}
    assert mc.evidence_key(a) == frozenset()
    assert [c.cid for c in mc.alias_group(clusters, "a")] == ["a"]
    assert len(mc.candidates(clusters, min_count=3, min_sessions=2, include_resolved=False)) == 2


# ------------------------------------------------------------------- pruning


def _cl(**kw) -> "mc.Cluster":
    base = dict(cid="x", term="t", count=1, sessions=["s"], last_seen="2026-01-01T00:00:00Z")
    base.update(kw)
    return mc.Cluster(**base)


@pytest.mark.parametrize(
    "cluster,expected,why",
    [
        (_cl(), True, "open, never recurred, silent for a year"),
        (_cl(last_seen="2026-11-01T00:00:00Z"), False, "still recent"),
        (_cl(count=3), False, "at threshold — the accumulating count IS the mechanism"),
        (_cl(status="dismissed"), False, "a verdict is never forgotten"),
        (_cl(status="accepted"), False, "a verdict is never forgotten"),
    ],
)
def test_prune_rule(cluster, expected, why):
    assert mc.prunable(cluster, now="2027-01-01T00:00:00Z") is expected, why


def test_state_forgets_only_stale_noise(tmp_path):
    clusters = {
        "keep-recent": _cl(cid="keep-recent", term="recent", last_seen="2026-12-20T00:00:00Z"),
        "keep-real": _cl(cid="keep-real", term="real", count=4),
        "keep-judged": _cl(cid="keep-judged", term="judged", status="dismissed"),
        "drop": _cl(cid="drop", term="stale"),
    }
    stored = mc.to_state(clusters, {}, now="2027-01-01T00:00:00Z")["clusters"]
    assert set(stored) == {"keep-recent", "keep-real", "keep-judged"}


def test_pruning_is_opt_in(tmp_path):
    """to_state without a clock keeps everything — a caller that cannot date the
    sweep must not silently drop history."""
    clusters = {"drop": _cl(cid="drop")}
    assert set(mc.to_state(clusters, {})["clusters"]) == {"drop"}
